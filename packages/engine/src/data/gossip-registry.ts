// 补充任务：八卦/传闻机制数据层
// 对应 log-filter.ts 的 gossip（八卦传闻）日志分类
// 机制说明：
//   - 玩家在 City/茶馆/坊市/街头等场合获取八卦
//   - 每条八卦有可信度（credibility），引擎可据此决定
//     传闻真假、情报价值与可解锁内容
//   - relatedEventId 关联奇遇事件：获知传闻后，对应事件
//     触发概率提升或解锁（引擎逻辑后续接入）
// 注：本数据文件的接口为自包含定义，无对应 @taosim/contracts 类型
// ============================================================

// 八卦类别：秘辛（可信度低但价值高）/ 流言（真假参半）/ 情报（实用）/ 传说（上古秘闻）
export type GossipCategory = 'secret' | 'rumor' | 'tip' | 'legend';
// 来源场合
export type GossipSource = 'teahouse' | 'market' | 'street' | 'npc' | 'ancient';

// 八卦的情报效果（引擎消费字段）
export interface GossipEffect {
  type:
    | 'unlockEvent'   // 解锁/提升某奇遇事件触发（value=事件 id）
    | 'weakness'      // 敌手弱点（value=目标描述）
    | 'treasureHint'  // 藏宝线索（value=地点描述）
    | 'favorability'  // 好感度修正（value=数值）
    | 'discount'      // 交易折扣（value=数值，如 '-0.1'）
    | 'recipe'        // 配方线索（value=配方 id）
    | 'location';     // 地点情报（value=地点描述）
  value: string;
  note?: string;
}

export interface GossipEntry {
  id: string;                // 如 'GOSSIP_SPIRIT_VEIN_MOUNT'
  title: string;             // 八卦标题
  text: string;              // 2-3 句叙事
  category: GossipCategory;
  source: GossipSource;
  credibility: number;       // 0-1，可信度
  effects?: GossipEffect[];
  relatedEventId?: string;   // 关联的奇遇事件 id（adventure-events.ts）
  // —— 原子引用（v2）：引用实体注册表，避免硬编码人名/地名 ——
  // 引擎可据此将八卦挂到具体 NPC 的信息面板，或按地点分类展示
  npcId?: string;            // 本条八卦涉及的具名 NPC（npc-registry.ts）
  locationId?: string;       // 本条八卦发生/指向的地点（location-registry.ts）
}

